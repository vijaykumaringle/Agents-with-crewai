#!/usr/bin/env python3
"""
Entry point for running the Cipher agent with CrewAI.
"""

import os
import datetime
from dotenv import load_dotenv
from crewai import Crew
from crewai import LLM
from cipher_agent import CipherAgent
from google_reviews import GoogleReviewsFetcher

# Load environment variables
load_dotenv()

def save_result_to_md(result, task_name="Analyze Google Reviews"):
    """Save the result to a markdown file with timestamp."""
    os.makedirs("results", exist_ok=True)
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"results/cipher_agent_result_{timestamp}.md"
    md_content = f"""# Cipher by Vijaykumar Analysis Report

**Generated:** {datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
**Task:** {task_name}
**Model:** Gemini 2.5 Flash

## Analysis Results

{result}

## Agent Details

- **Agent Type:** Cipher by Vijaykumar (Business Review Analyst)
- **Role:** Analyze Google reviews to extract insights and generate business improvement recommendations
- **Capabilities:** 
  - Fetch Google reviews
  - Perform sentiment analysis
  - Extract pros and cons
  - Generate improvement plans

---
*Report generated by Cipher by Vijaykumar using Agentic AI*
"""
    with open(filename, 'w', encoding='utf-8') as f:
        f.write(md_content)
    return filename

def main():
    # Prompt for business name
    business_name = input("Enter the business name to analyze: ").strip()
    if not business_name:
        print("❌ Business name is required.")
        return

    api_key = os.getenv("GOOGLE_API_KEY")
    if not api_key:
        print("❌ GOOGLE_API_KEY not set in environment.")
        return

    # Fetch Google reviews
    try:
        print(f"\n🔎 Fetching Google reviews for: {business_name} ...")
        reviews = GoogleReviewsFetcher.fetch_reviews(
            GoogleReviewsFetcher.fetch_place_id(business_name, api_key),
            api_key,
            num_reviews=20
        )
        if not reviews:
            print(f"❌ No reviews found for '{business_name}'.")
            return
    except Exception as e:
        error_msg = f"Error fetching reviews: {str(e)}"
        print(f"❌ {error_msg}")
        filename = save_result_to_md(error_msg, f"Error fetching reviews for {business_name}")
        print(f"📝 Error report saved to: {filename}")
        return

    # Initialize Gemini LLM
    llm = LLM(
        model="gemini/gemini-2.5-flash",
        api_key=api_key
    )
    agent = CipherAgent(llm=llm)

    # Analyze sentiment
    analyzed_reviews = agent.analyze_sentiment(reviews)
    # Extract pros and cons
    pros, cons = agent.extract_pros_cons(analyzed_reviews)
    # Generate improvement plan
    improvement_plan = agent.generate_improvement_plan(pros, cons)

    # Compose final result
    result = f"""
### Business: {business_name}

#### Reviews Analyzed: {len(reviews)}

#### Pros:
- {'\n- '.join(pros) if pros else 'None'}

#### Cons:
- {'\n- '.join(cons) if cons else 'None'}

#### Improvement Plan:
{improvement_plan}
"""

    filename = save_result_to_md(result, f"Google Review Analysis for {business_name}")
    print(f"\n✅ Report saved to: {filename}")

if __name__ == "__main__":
    main() 